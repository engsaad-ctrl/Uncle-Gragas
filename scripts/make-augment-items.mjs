// Writes src/app/augmentItemsData.ts: what each augment does to each item across champions, from ARAMKit (aramkit.com).
// Run once per patch, by hand, never from the app: 80 requests with a pause between them, kept short because the site's
// terms forbid bulk scraping. Files already in the folder aren't asked for again, so use a new folder for a new patch.
//   node scripts/make-augment-items.mjs <folder>

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) throw new Error('usage: node scripts/make-augment-items.mjs <folder>');
mkdirSync(dir, { recursive: true });

// The 40 champions played most in our games, on patch 16.21: the per-augment file of each is about 3.8 MB.
const CHAMPIONS = [17, 18, 21, 22, 25, 29, 30, 31, 35, 36, 45, 50, 51, 53, 54, 63, 67, 76, 81, 90, 99, 101, 103, 110, 111, 136, 143, 145, 147, 161, 202, 222, 223, 235, 236, 412, 800, 804, 875, 901];
const MIN_GAMES = 1000;
const PRIOR_GAMES = 500; // few games across champions stay near nothing
const SMALLEST = 0.2; // points; less than this moves no item
const BOUGHT_AS = { 3042: 3004, 3040: 3003, 3121: 3119 };
const tail = (id) => BOUGHT_AS[id % 10000] ?? id % 10000;
const logit = (p) => Math.log(p / (1 - p));
const points = (wr, rate) => 25 * (logit(Math.min(0.99, Math.max(0.01, wr))) - logit(rate));

const headers = { 'user-agent': 'Mozilla/5.0' };
const version = /data\/(\d+\.\d+-\d+-[0-9a-f]{6,})/.exec(await (await fetch('https://aramkit.com/en-US', { headers })).text())?.[1];
if (!version) throw new Error('no data version on the page');
const row = (x) => [x.id, x.sampleCount, x.winRate];
async function file(name, url, shrink) {
  const path = join(dir, name);
  if (existsSync(path)) return JSON.parse(readFileSync(path, 'utf8'));
  await new Promise((r) => setTimeout(r, 1500));
  const res = await fetch(url, { headers });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const value = shrink(await res.json());
  writeFileSync(path, JSON.stringify(value));
  return value;
}

const totals = new Map();
for (const c of CHAMPIONS) {
  const base = `https://data.aramkit.com/data/${version}/stats/all/champion-details/${c}`;
  const detail = await file(`d${c}.json`, `${base}.json`, (j) => ({ n: j.champion.stats.sampleCount, w: j.champion.stats.winRate, a: j.augments.all.map(row), i: j.items.unfiltered.all.map(row) }));
  const single = await file(`s${c}.json`, `${base}-single-augments.json`, (j) => j.items.map((x) => [x.augmentId, x.all.map(row)]));
  const items = new Map(detail.i.map(([id, n, w]) => [id % 10000, [n, w]]));
  const augments = new Map(detail.a.map(([id, n, w]) => [id, [n, w]]));
  for (const [augment, list] of single) {
    const a = augments.get(augment);
    if (!a) continue;
    const rows = list.flatMap(([id, n, w]) => { const b = items.get(id % 10000); return b && n >= MIN_GAMES ? [{ id: tail(id), n, d: points(w, a[1]) - points(b[1], detail.w) }] : []; });
    if (rows.length < 3) continue;
    // Inside one champion and augment: what the pair itself is worth doesn't count.
    const mean = rows.reduce((t, r) => t + r.d, 0) / rows.length;
    for (const r of rows) {
      const key = `${augment}:${r.id}`;
      const t = totals.get(key) ?? { w: 0, s: 0 };
      t.w += r.n;
      t.s += r.n * (r.d - mean);
      totals.set(key, t);
    }
  }
}

const table = {};
for (const [key, t] of totals) {
  const value = Math.round((10 * t.s) / (t.w + PRIOR_GAMES)) / 10;
  if (Math.abs(value) < SMALLEST) continue;
  const [augment, item] = key.split(':');
  (table[augment] ??= {})[item] = value;
}
writeFileSync(
  new URL('../src/app/augmentItemsData.ts', import.meta.url),
  `// Generated by scripts/make-augment-items.mjs from ARAMKit, ${version}. Augment id, then the item's last four digits: points\n// that item wins more or less with the augment than the champion's other items, across champions.\nexport const AUGMENT_ITEMS: Record<number, Record<number, number>> = ${JSON.stringify(table)};\n`,
);
console.log(`${Object.keys(table).length} augments, ${Object.values(table).reduce((t, x) => t + Object.keys(x).length, 0)} pairs`);
