// Augments out of Mayhem: listed in the game files but picked by nobody in the stored games of the last patches (the owner, 2026-11-07:
// Grandma's Chili Oil was picked 19 times in 16.4 to 16.11 and never since, yet the engine ranked it first for everyone).
// Rule (knowledge/fight-rules.md, augments): an augment picked 0 times in the latest patches that together hold 20,000 or more stored games is retired.
// Three patches let 16.20's 649 games keep alive the 10 augments the wiki says were removed in 16.21 (Dropkick, DropBear, High Roller...). Run from the repo root after the build: node scripts/make-retired-augments.mjs
import { pathToFileURL } from 'node:url';
import { readFileSync, writeFileSync } from 'node:fs';
const imp = (p) => import(pathToFileURL(`${process.cwd()}/dist/${p}`).href);
const { createServices } = await imp('main/services.js');
const s = createServices({ cacheDir: `${process.env.APPDATA}/LOL_helper`, fetchImpl: fetch });
const augs = (await s.augments()).augments.filter((a) => a.modes.includes('mayhem'));
const games = JSON.parse(readFileSync(`${process.env.APPDATA}/LOL_helper/mayhem-games.json`, 'utf8'));
const patch = (g) => g.version.split('.').slice(0, 2).join('.');
const order = (p) => p.split('.').map(Number).reduce((a, b) => a * 100 + b, 0);
const MIN_GAMES = 20000;
const byPatch = new Map(); for (const g of games) byPatch.set(patch(g), (byPatch.get(patch(g)) ?? 0) + 1);
const recent = []; let held = 0;
for (const p of [...byPatch.keys()].sort((a, b) => order(b) - order(a))) { if (held >= MIN_GAMES) break; recent.push(p); held += byPatch.get(p); }
const picks = new Map(); let n = 0;
for (const g of games) if (recent.includes(patch(g))) { n++; for (const p of g.players) for (const id of p.augments ?? []) picks.set(id, (picks.get(id) ?? 0) + 1); }
const count = (a) => a.ids.reduce((t, id) => t + (picks.get(id) ?? 0), 0);
const live = augs.map(count).filter((c) => c > 0).sort((a, b) => a - b);
if (held < MIN_GAMES) throw new Error(`only ${held} stored games: 0 picks could be an accident, collect more`);
const retired = augs.filter((a) => count(a) === 0).sort((a, b) => a.enName.localeCompare(b.enName));
writeFileSync('src/ai/retiredAugments.ts', `// Generated by scripts/make-retired-augments.mjs on ${new Date().toISOString().slice(0, 10)}: patches ${recent.join(', ')}, ${n} stored games, rarest augment still picked ${live[0]} times.
// Augments in the game files that nobody picked there: out of Mayhem, so the engine neither ranks nor suggests them.
export const RETIRED_AUGMENTS: ReadonlySet<number> = new Set([
${retired.map((a) => `  ${a.ids.join(', ')}, // ${a.enName}`).join('\n')}
]);
`);
console.log(`patches ${recent.join(', ')}, ${n} games; retired ${retired.length} of ${augs.length}; rarest still picked ${live[0]}`);
