const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('lolh', {
  getAugments: () => ipcRenderer.invoke('augments:get'),
  listChampions: () => ipcRenderer.invoke('champions:list'),
  championPage: (id, mode, position) => ipcRenderer.invoke('champion:page', id, mode, position),
  listItems: (mode) => ipcRenderer.invoke('items:list', mode),
  tierList: (position, mode) => ipcRenderer.invoke('tierlist:get', position, mode),
  lcuState: () => ipcRenderer.invoke('lcu:state'),
  applyToClient: (id, mode, position, flash) => ipcRenderer.invoke('lcu:apply', id, mode, position, flash ?? null),
  suggestions: (position, enemies, taken) => ipcRenderer.invoke('suggest:get', position, enemies, taken),
  profile: (puuid) => ipcRenderer.invoke('profile:get', puuid ?? null),
  onLcuState: (callback) => ipcRenderer.on('lcu:state', (_event, state) => callback(state)),
  exportDiagnostics: () => ipcRenderer.invoke('diagnostics:export'),
  overlayData: () => ipcRenderer.invoke('overlay:data'),
  hideOverlay: () => ipcRenderer.invoke('overlay:hide'),
  setOverlayLarge: (on) => ipcRenderer.invoke('overlay:large', on === true),
  aiBuild: (championId, augmentIds) => ipcRenderer.invoke('ai:build', championId, augmentIds),
  lastAiPicks: () => ipcRenderer.invoke('ai:last'),
  augmentFit: (augmentIds) => ipcRenderer.invoke('mayhem:fit', augmentIds),
  augmentEffects: () => ipcRenderer.invoke('mayhem:effects'),
  engineBuild: (championId, augmentIds) => ipcRenderer.invoke('build:engine', championId, augmentIds),
  hasAiKey: () => ipcRenderer.invoke('ai:key:has'),
  setAiKey: (key) => ipcRenderer.invoke('ai:key:set', key),
  clearAiKey: () => ipcRenderer.invoke('ai:key:clear'),
  setOverlayEnabled: (on) => ipcRenderer.invoke('overlay:enabled', on === true),
  gameWindowMode: () => ipcRenderer.invoke('game:windowMode'),
  setBorderless: () => ipcRenderer.invoke('game:borderless'),
  updateStatus: () => ipcRenderer.invoke('update:status'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  onUpdateStatus: (callback) => ipcRenderer.on('update:status', (_event, status) => callback(status)),
  onOverlayShow: (callback) => ipcRenderer.on('overlay:show', (_event, tab) => callback(tab)),
  gameTeams: () => ipcRenderer.invoke('game:teams'),
});
